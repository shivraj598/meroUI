// Generates src/lib/componentSourceData.ts — a static map of component slug
// to raw source text, read from src/components/ui/*.tsx at generation time.
// The docs pages use this map at runtime (and during pre-render) instead of
// poking the filesystem, which does not exist inside the Cloudflare Worker.
import fs from "node:fs";
import path from "node:path";

const UI_DIR = path.join(process.cwd(), "src", "components", "ui");
const OUT = path.join(process.cwd(), "src", "lib", "componentSourceData.ts");

const kebab = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const entries = fs
  .readdirSync(UI_DIR)
  .filter((f) => f.endsWith(".tsx"))
  .sort()
  .map((file) => {
    const slug = kebab(file.slice(0, -4));
    const source = fs.readFileSync(path.join(UI_DIR, file), "utf8");
    return `  ${JSON.stringify(slug)}: ${JSON.stringify(source)},`;
  });

const banner = `// AUTO-GENERATED by scripts/generate-component-source.mjs — do not edit.
// Run \`npm run gen:components\` after adding or editing files in src/components/ui.
export const COMPONENT_SOURCES: Record<string, string> = {
${entries.join("\n")}
};
`;

fs.writeFileSync(OUT, banner);
console.log(`Generated ${OUT} (${entries.length} components)`);